const { expect, test } = require('@playwright/test');
const { createProfile, startWorkout } = require('./helpers.cjs');

test('workout heading is compact and progress covers every session stage', async ({ page }) => {
  test.setTimeout(60_000);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:390,height:844});
  await page.clock.install({time:new Date('2026-11-03T09:00:00Z')});
  await page.clock.pauseAt(new Date('2026-11-03T09:00:01Z'));
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await createProfile(page);
  await startWorkout(page);
  const segments=await page.evaluate(()=>JSON.parse(localStorage.getItem('scirun.activeTimer')).segments);
  const total=segments.length;
  expect(segments[0].type).toBe('warmup');
  expect(segments.at(-1).type).toBe('cooldown');
  expect(segments.some(s=>s.type==='walk')).toBe(true);
  expect(total).toBeGreaterThan(segments.filter(s=>s.type==='run').length);
  await expect(page.locator('#workoutViewTitle')).toHaveText('Săptămâna 1 · Antrenamentul 1');
  await expect(page.locator('.workout-heading .eyebrow')).toHaveCount(0);
  await expect(page.locator('.workout-heading #timerState')).toHaveText('ÎN DESFĂȘURARE');
  await expect(page.locator('#workoutRing #timerState')).toHaveCount(0);
  await expect(page.locator('#roundCount')).toHaveText('Etapa 1 / '+total);
  await expect(page.locator('#roundBar [data-stage-index]')).toHaveCount(total);
  expect(await page.locator('#roundBar [data-stage-index]').evaluateAll(nodes=>nodes.map(el=>el.dataset.phase))).toEqual(segments.map(s=>s.type));
  await expect(page.locator('.session-progress-legend')).toContainText('Încălzire');
  await expect(page.locator('.session-progress-legend')).toContainText('Mers');
  await expect(page.locator('.session-progress-legend')).toContainText('Revenire');
  await expect(page.locator('#roundBar')).toHaveAttribute('aria-valuemax',String(total));

  await page.locator('#workoutSkip').click();
  await expect(page.locator('#roundCount')).toHaveText('Etapa 2 / '+total);
  await expect(page.locator('#roundBar [data-stage-index="0"]')).toHaveAttribute('data-status','complete');
  await page.locator('#workoutSkip').click();
  await expect(page.locator('#roundCount')).toHaveText('Etapa 3 / '+total);
  await expect(page.locator('#roundBar [data-stage-index="2"]')).toHaveAttribute('data-phase','walk');
  await page.clock.fastForward(segments[2].seconds*500);
  await expect(page.locator('#roundBar')).toHaveAttribute('aria-valuenow','2.5');
  const widths=await page.locator('#roundBar [data-stage-index="2"]').evaluate(el=>({track:el.clientWidth,fill:el.querySelector('.session-progress-fill').getBoundingClientRect().width}));
  expect(widths.fill).toBeCloseTo(widths.track/2,0);
  await page.locator('#workoutPause').click();
  await expect(page.locator('.workout-heading #timerState')).toHaveText('ÎN PAUZĂ');
  await page.clock.fastForward(10_000);
  await expect(page.locator('#roundBar')).toHaveAttribute('aria-valuenow','2.5');
  await page.reload();
  await expect(page.locator('.workout-heading #timerState')).toHaveText('ÎN PAUZĂ');
  await expect(page.locator('#roundCount')).toHaveText('Etapa 3 / '+total);
  await expect(page.locator('#roundBar')).toHaveAttribute('aria-valuenow','2.5');
  await page.screenshot({path:'test-results/session-heading-progress.png',fullPage:true});

  await page.evaluate(()=>localStorage.setItem('scirun.lang','en'));
  await page.reload();
  await expect(page.locator('#workoutViewTitle')).toHaveText('Week 1 · Workout 1');
  await expect(page.locator('.workout-heading #timerState')).toHaveText('PAUSED');
  await page.locator('#workoutPause').click();
  const toCooldown=await page.evaluate(()=>{
    const timer=JSON.parse(localStorage.getItem('scirun.activeTimer'));
    return (timer.remaining+timer.segments.slice(timer.index+1,-1).reduce((sum,s)=>sum+s.seconds,0))*1000+1000;
  });
  await page.clock.fastForward(toCooldown);
  await expect(page.locator('#roundCount')).toHaveText('Stage '+total+' / '+total);
  await expect(page.locator('#roundBar [data-stage-index="'+(total-1)+'"]')).toHaveAttribute('data-phase','cooldown');
  await expect(page.locator('#roundBar [data-stage-index="'+(total-1)+'"]')).toHaveAttribute('data-status','current');
  await expect(page.locator('#roundBar [data-status="complete"]')).toHaveCount(total-1);
  await page.screenshot({path:'test-results/session-progress-cooldown.png',fullPage:true});
  expect(errors).toEqual([]);
});
